import { chromium } from 'playwright';
import fs from 'node:fs/promises';
(async () => {
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage(); const errors=[];
 page.on('pageerror',e=>{errors.push(e.message);console.error('PAGEERROR',e.message)});
 const base=process.env.TEST_URL || 'http://localhost:4174';
 const probe=await page.request.get(base, { maxRedirects: 10 });
 if(!probe.ok()) throw Error(`HTTP ${probe.status()} ${((await probe.text()) ?? '').slice(0, 4000)}`);
 const response=await page.goto(base,{waitUntil:'networkidle'});
 if(!response || response.status()!==200) throw Error(`HTTP ${response?.status() ?? 'unknown'} route navigation failed`);
 await page.getByRole('heading',{name:'Question Inventory',exact:true}).waitFor();
 const cards=page.locator('.inventory-question-card[data-question-id]');
 if(await cards.count()===0) throw Error('No questions');
 await page.getByLabel('Reviewer comment',{exact:true}).first().fill('Cloudflare deployment smoke test');
 await page.getByRole('button',{name:'Save comment',exact:true}).first().click();
 await page.reload({waitUntil:'networkidle'});
 await page.getByText('Cloudflare deployment smoke test',{exact:true}).first().waitFor();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download feedback JSON'}).click();
 const download=await downloadPromise;
 const data=JSON.parse(await fs.readFile(await download.path(),'utf8'));
 if(data.schemaVersion !== 2 || !data.batches.length || !data.batches[0].release.sha256) throw Error('Invalid feedback export');
 if(data.batches.some(batch => Object.values(batch.questions).some(q => 'draft' in q))) throw Error('Draft leaked');
 const currentBatch = data.batches.find(batch => batch.release?.contentVersion === batch.contentVersion);
 const currentId = Object.keys(currentBatch.questions)[0];
 await page.evaluate(({batch,id}) => {
   const oldVersion = 'a'.repeat(64);
   const oldQuestion = { entries: [{...batch.questions[id].entries[0], comment: 'Old-version-only review'}] };
   localStorage.setItem(`new-horizon-review-v2:${oldVersion}:${id}`, JSON.stringify(oldQuestion));
   localStorage.setItem(`new-horizon-review-release:${oldVersion}`, JSON.stringify({...batch.release, contentVersion: oldVersion}));
   localStorage.setItem(`new-horizon-review:${id}`, JSON.stringify(oldQuestion));
 }, {batch:currentBatch,id:currentId});
 await page.reload({waitUntil:'networkidle'});
 if(await page.getByText('Old-version-only review',{exact:true}).count()) throw Error('Old reviews leaked into current version');
 const allDownloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download feedback JSON'}).click();
 const allDownload=await allDownloadPromise;
 const archived=JSON.parse(await fs.readFile(await allDownload.path(),'utf8'));
 if(archived.batches.length!==3 || !archived.batches.some(batch=>batch.contentVersion==='legacy-unversioned' && batch.release===null)) throw Error('Archived/legacy review export failed');
 await page.getByRole('link',{name:'TH',exact:true}).click();
 await page.waitForURL('**/*lang=th*');
 await page.waitForLoadState('networkidle');
 if(!page.url().includes('lang=th')) throw Error('Thai link failed '+page.url());
 await page.setViewportSize({width:390,height:844});
 await fs.mkdir('work/inventory-tests', { recursive: true });
 await page.screenshot({path:'work/inventory-tests/mobile.png',fullPage:false});
 const id=await cards.first().getAttribute('data-question-id');
 await page.getByRole('textbox',{name:'Search',exact:true}).fill(id);
 await page.getByRole('button',{name:'Apply filters'}).click();
 await page.waitForURL('**/*q=*');
 if(await cards.count()!==1) throw Error('Question search failed');
 const assets=await page.locator('img[src],audio[src],video[src],source[src]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('src')));
 for(const asset of assets) { const result=await page.request.get(new URL(asset,base).href); if(!result.ok()) throw Error('Asset failed '+asset); }
 const blocked=await page.request.get(base+'/admin');
 if(blocked.status()!==404) throw Error('Unexpected admin route '+blocked.status());
 if(errors.length) throw Error(errors.join('\n'));
 console.log(JSON.stringify({url:page.url(),cards:await cards.count(),feedbackExport:true,admin404:true,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
